import type { SvgProcessResult } from './types.js'

const CAMEL_ATTR_MAP: Record<string, string> = {
  'class': 'className',
  'fill-rule': 'fillRule',
  'clip-rule': 'clipRule',
  'clip-path': 'clipPath',
  'stroke-width': 'strokeWidth',
  'stroke-linecap': 'strokeLinecap',
  'stroke-linejoin': 'strokeLinejoin',
  'stroke-dasharray': 'strokeDasharray',
  'stroke-dashoffset': 'strokeDashoffset',
  'stroke-miterlimit': 'strokeMiterlimit',
  'stroke-opacity': 'strokeOpacity',
  'fill-opacity': 'fillOpacity',
  'stop-color': 'stopColor',
  'stop-opacity': 'stopOpacity',
  'font-family': 'fontFamily',
  'font-size': 'fontSize',
  'font-weight': 'fontWeight',
  'text-anchor': 'textAnchor',
  'xlink:href': 'xlinkHref',
  'xml:space': 'xmlSpace',
}

function byteLen(str: string): number {
  return typeof Buffer !== 'undefined' ? Buffer.byteLength(str, 'utf8') : str.length
}

function toBase64(str: string): string {
  if (typeof Buffer !== 'undefined') {
    return Buffer.from(str, 'utf8').toString('base64')
  }
  const bytes = new TextEncoder().encode(str)
  let bin = ''
  for (let i = 0; i < bytes.length; i++) {
    bin += String.fromCharCode(bytes[i])
  }
  return btoa(bin)
}

export function optimizeSvgSource(rawInput: string, precision: number = 2): SvgProcessResult {
  const trimmed = String(rawInput || '').trim()
  if (!trimmed) {
    throw new Error('EMPTY_SVG_INPUT: SVG 源码不能为空')
  }

  const svgOpenMatch = trimmed.match(/<svg[\s>]/i)
  const svgCloseMatch = trimmed.match(/<\/svg\s*>/i)
  if (!svgOpenMatch || !svgCloseMatch) {
    throw new Error('INVALID_SVG_DOCUMENT: 未找到合法的 <svg>...</svg> 根节点')
  }

  let removedDangerousNodes = 0
  let working = trimmed

  // Strip XML prolog, DOCTYPE, and comments
  working = working.replace(/<\?xml[\s\S]*?\?>/gi, '')
  working = working.replace(/<!DOCTYPE[\s\S]*?>/gi, '')
  working = working.replace(/<!--[\s\S]*?-->/g, '')

  // Security sanitization: strip <script>, <foreignObject>, and on* event handlers
  working = working.replace(/<script\b[\s\S]*?<\/script\s*>/gi, () => {
    removedDangerousNodes++
    return ''
  })
  working = working.replace(/<foreignObject\b[\s\S]*?<\/foreignObject\s*>/gi, () => {
    removedDangerousNodes++
    return ''
  })
  working = working.replace(/\s+on[a-z]+\s*=\s*(?:"[^"]*"|'[^']*'|[^\s>]+)/gi, () => {
    removedDangerousNodes++
    return ''
  })
  working = working.replace(
    /\s+(?:href|xlink:href)\s*=\s*(?:"\s*javascript:[^"]*"|'\s*javascript:[^']*')/gi,
    () => {
      removedDangerousNodes++
      return ''
    },
  )

  // Strip editor metadata tags and attributes (Sketch, Inkscape, Sodipodi, Adobe Illustrator)
  working = working.replace(/<metadata\b[\s\S]*?<\/metadata\s*>/gi, '')
  working = working.replace(/<(?:sodipodi|inkscape):[a-zA-Z0-9_-]+\b[\s\S]*?(?:\/>|<\/(?:sodipodi|inkscape):[a-zA-Z0-9_-]+\s*>)/gi, '')
  working = working.replace(/\s+(?:xmlns:(?:sketch|inkscape|sodipodi|dc|cc|rdf)|sketch:[a-zA-Z0-9_-]+|inkscape:[a-zA-Z0-9_-]+|sodipodi:[a-zA-Z0-9_-]+|data-name)\s*=\s*(?:"[^"]*"|'[^']*')/gi, '')

  // Round high-precision floating point numbers in coordinates/paths
  const factor = Math.pow(10, Math.max(0, Math.min(4, precision)))
  working = working.replace(/-?\d+\.\d{3,}/g, (numStr) => {
    const num = Number(numStr)
    if (!Number.isFinite(num)) return numStr
    return String(Math.round(num * factor) / factor)
  })

  // Collapse redundant whitespace between tags and inside attributes
  working = working
    .replace(/>\s+</g, '><')
    .replace(/\s{2,}/g, ' ')
    .trim()

  const viewBoxMatch = working.match(/viewBox\s*=\s*["']([^"']+)["']/i)
  const viewBox = viewBoxMatch ? viewBoxMatch[1] : '0 0 24 24'
  const pathCount = Array.from(working.matchAll(/<(?:path|circle|rect|polygon|polyline|line|ellipse)\b/gi)).length

  const originalBytes = byteLen(trimmed)
  const optimizedBytes = byteLen(working)
  const savedBytes = Math.max(0, originalBytes - optimizedBytes)
  const savedPercentage =
    originalBytes > 0 ? Math.round((savedBytes / originalBytes) * 1000) / 10 : 0

  let jsxBody = working
  for (const [kebab, camel] of Object.entries(CAMEL_ATTR_MAP)) {
    const attrRegex = new RegExp(`\\b${kebab.replace(':', '\\:')}=`, 'g')
    jsxBody = jsxBody.replace(attrRegex, `${camel}=`)
  }
  jsxBody = jsxBody.replace(/^<svg\b/i, '<svg {...props}')

  const reactTsxCode = [
    "import React from 'react'",
    '',
    'export function SvgIcon(props: React.SVGProps<SVGSVGElement>): React.ReactElement {',
    `  return (${jsxBody})`,
    '}',
    '',
    'export default SvgIcon',
  ].join('\n')

  const vueSfcCode = [
    '<template>',
    `  ${working}`,
    '</template>',
    '',
    '<script setup lang="ts">',
    '// Generated by ZTools SVG Icon Studio',
    '</script>',
  ].join('\n')

  const dataUri = `data:image/svg+xml;utf8,${encodeURIComponent(working)}`
  const base64DataUri = `data:image/svg+xml;base64,${toBase64(working)}`

  return {
    originalSvg: trimmed,
    optimizedSvg: working,
    reactTsxCode,
    vueSfcCode,
    dataUri,
    base64DataUri,
    metrics: {
      originalBytes,
      optimizedBytes,
      savedBytes,
      savedPercentage,
      viewBox,
      pathCount,
      removedDangerousNodes,
    },
  }
}
