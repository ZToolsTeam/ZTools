import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { pinyin } from 'pinyin-pro'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const outputPath = path.resolve(__dirname, '../native/ztools-indexer/pinyin_table.hpp')

const RANGE_START = 0x4e00
const RANGE_END = 0x9fff
const COUNT = RANGE_END - RANGE_START + 1

const syllableList = ['']
const syllableToIdx = new Map([['', 0]])
const indices = new Uint16Array(COUNT)

let mappedCount = 0
for (let cp = RANGE_START; cp <= RANGE_END; cp++) {
  const ch = String.fromCodePoint(cp)
  const raw = String(pinyin(ch, { toneType: 'none', v: true }) || '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z]/g, '')
  if (!raw) {
    indices[cp - RANGE_START] = 0
    continue
  }
  let idx = syllableToIdx.get(raw)
  if (idx === undefined) {
    idx = syllableList.length
    syllableToIdx.set(raw, idx)
    syllableList.push(raw)
  }
  indices[cp - RANGE_START] = idx
  mappedCount++
}

const lines = []
lines.push('#pragma once')
lines.push('')
lines.push('// Auto-generated by electron-client/scripts/generate-pinyin-table.mjs from pinyin-pro.')
lines.push(`// Covers U+4E00..U+9FFF (${COUNT} codepoints, ${mappedCount} mapped, ${syllableList.length - 1} unique syllables).`)
lines.push('#include <cstdint>')
lines.push('#include <string_view>')
lines.push('')
lines.push('namespace ztools::indexer::pinyin_data {')
lines.push('')
lines.push(`inline constexpr uint32_t kHanziRangeStart = 0x${RANGE_START.toString(16).toUpperCase()}u;`)
lines.push(`inline constexpr uint32_t kHanziRangeEnd = 0x${RANGE_END.toString(16).toUpperCase()}u;`)
lines.push(`inline constexpr size_t kSyllableCount = ${syllableList.length};`)
lines.push('')
lines.push('inline constexpr const char* kSyllables[kSyllableCount] = {')
for (let i = 0; i < syllableList.length; i += 12) {
  const chunk = syllableList.slice(i, i + 12).map(s => `"${s}"`).join(', ')
  lines.push(`  ${chunk}${i + 12 < syllableList.length ? ',' : ''}`)
}
lines.push('};')
lines.push('')
lines.push(`inline constexpr uint16_t kHanziToSyllable[${COUNT}] = {`)
for (let i = 0; i < COUNT; i += 24) {
  const chunk = Array.from(indices.subarray(i, Math.min(COUNT, i + 24))).join(',')
  lines.push(`  ${chunk}${i + 24 < COUNT ? ',' : ''}`)
}
lines.push('};')
lines.push('')
lines.push('inline std::string_view LookupHanziPinyin(uint32_t cp) noexcept {')
lines.push('  if (cp < kHanziRangeStart || cp > kHanziRangeEnd) return {};')
lines.push('  const uint16_t idx = kHanziToSyllable[cp - kHanziRangeStart];')
lines.push('  return (idx < kSyllableCount) ? std::string_view(kSyllables[idx]) : std::string_view{};')
lines.push('}')
lines.push('')
lines.push('} // namespace ztools::indexer::pinyin_data')
lines.push('')

fs.writeFileSync(outputPath, lines.join('\n'), 'utf8')
console.log(`Generated ${outputPath}: ${mappedCount}/${COUNT} hanzi mapped across ${syllableList.length - 1} syllables (${Buffer.byteLength(lines.join('\n'))} bytes)`)
